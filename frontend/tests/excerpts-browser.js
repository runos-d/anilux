async page => {
  const origin = 'http://localhost:5181', api = 'http://localhost:8015/api';
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const report = {}, pageErrors = [], writes = [];
  page.on('pageerror', error => pageErrors.push(error.message));
  page.on('request', request => {
    if (request.method() !== 'GET' && /episode-progress|users\/library|active-tab/.test(request.url())) writes.push(request.url());
  });
  const iframe = `<!doctype html><html><body style="background:#141414;color:white"><button id="start">Воспроизвести тестовую серию</button><script>
    let time = 0, playing = false, since = performance.now(); window.pauseSamples = []; window.commands = [];
    const current = () => time + (playing ? (performance.now() - since) / 1000 : 0);
    const send = (key, value) => parent.postMessage({key:'kodik_player_'+key,value}, '*');
    function play() { since=performance.now(); playing=true; send('current_episode', {episode:location.search.includes('only_episode') ? null : 3,season:location.search.includes('only_episode') ? null : 2,translation:{id:77,title:'Тестовая озвучка'}});send('duration_update',1200.5);send('video_started');send('play'); }
    document.querySelector('#start').onclick=play;
    window.setTestTime = value => {time=value;since=performance.now();playing=false};
    window.addEventListener('message', event => { const value=event.data?.value; if(event.data?.key!=='kodik_player_api')return;window.commands.push(value); if(value.method==='get_time')send('time',current());if(value.method==='seek'){time=value.seconds;since=performance.now();send('seek',{time})}if(value.method==='play')play();if(value.method==='pause'){time=current();playing=false;window.pauseSamples.push(time);send('pause')} });
    setInterval(()=>{if(playing)send('time_update',Math.round(current()))},1000);
  <\/script></body></html>`;
  await page.route('https://kodikplayer.com/**', route => route.fulfill({ contentType: 'text/html', body: iframe }));
  await page.goto(origin);
  const login = await page.request.post(api + '/users/login/', { data: { username: 'excerpt_browser_owner', password: 'Excerpt-Isolated-20261012!' } });
  assert(login.ok(), 'Isolated fixture login failed'); const owner = await login.json();
  await page.evaluate(owner => {
    localStorage.setItem('anilux_user_v1', JSON.stringify(owner.user));
    localStorage.setItem('anilux_access_token_v1', owner.tokens.access); localStorage.setItem('anilux_refresh_token_v1', owner.tokens.refresh);
  }, owner);
  const headers = { Authorization: 'Bearer ' + owner.tokens.access };
  const animes = await (await page.request.get(api + '/anime/attachment-search/', { params: { q: 'Проверка отрывков' } })).json();
  const anime = (animes.results || animes)[0]; assert(anime?.id, 'No fixture anime');
  await page.setViewportSize({ width: 1365, height: 950 });
  await page.goto(origin + `/anime/${anime.id}/watch?episode=3&season=2`);
  await page.frameLocator('.kodik-iframe').getByRole('button').click();
  const frame = page.frames().find(frame => frame.url().includes('kodikplayer.com'));
  await frame.evaluate(() => window.setTestTime(10.2525));
  await page.getByRole('button', { name: /^Начало отрывка/ }).click();
  await page.getByRole('button', { name: /^Конец отрывка/ }).waitFor({ state: 'visible' });
  await page.waitForFunction(() => ![...document.querySelectorAll('.capture button')][1].disabled);
  await frame.evaluate(() => window.setTestTime(11.7575));
  await page.getByRole('button', { name: /^Конец отрывка/ }).click();
  await page.getByLabel('Название (необязательно)').fill('Браузерный отрывок');
  await page.getByLabel('Описание (необязательно)').fill('Описание для поиска и карточек');
  const createResponse = page.waitForResponse(response => response.url().endsWith('/anime/excerpts/') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Сохранить отрывок', exact: true }).click();
  const saved = await (await createResponse).json(); assert(saved.id && saved.start === 10.2525 && saved.end === 11.7575 && saved.episode === 3 && saved.season === 2 && saved.translation_id === 77, 'Wrong captured material/range');
  report.creation = 'UI: fractional capture, optional fields, actual episode/translation';
  await page.goto(origin + '/excerpts');
  await page.getByRole('heading', { name: 'Мои отрывки' }).waitFor();
  await page.getByPlaceholder('Аниме, название или описание').fill('Браузерный');
  await page.locator('article').filter({ hasText: 'Браузерный отрывок' }).waitFor();
  const card = page.locator('article').filter({ hasText: 'Браузерный отрывок' });
  await card.getByRole('button', { name: 'Редактировать' }).click();
  await card.getByLabel('Конец отрывка вручную').fill('12.25');
  await card.getByRole('button', { name: 'Сохранить отрывок' }).click();
  await card.getByRole('button', { name: 'Включить ссылку' }).click();
  await card.getByRole('button', { name: 'Отключить ссылку' }).waitFor();
  const shared = await (await page.request.get(api + `/anime/excerpts/${saved.id}/`, { headers })).json();
  const libraryBefore = await (await page.request.get(api + '/users/library/', { headers })).json();
  writes.splice(0);
  await page.goto(origin + shared.share_path);
  await page.frameLocator('.kodik-iframe').getByRole('button').click();
  const playbackFrame = page.frames().find(frame => frame.url().includes('kodikplayer.com'));
  await page.waitForTimeout(2500);
  const samples = await playbackFrame.evaluate(() => ({ stops: window.pauseSamples, commands: window.commands }));
  const stop = samples.stops.find(time => time >= shared.end);
  assert(stop !== undefined && stop - shared.end < .4, 'Stop exceeded 400ms on mocked browser transport');
  report.mockStopOvershootSeconds = +(stop - shared.end).toFixed(4);
  await page.getByRole('button', { name: 'Повторить отрывок' }).click();
  await page.waitForTimeout(2500);
  assert((await playbackFrame.evaluate(() => window.pauseSamples)).filter(time => time >= shared.end).length >= 2, 'Repeat did not stop again');
  const libraryAfter = await (await page.request.get(api + '/users/library/', { headers })).json();
  assert(JSON.stringify(libraryBefore) === JSON.stringify(libraryAfter), 'Excerpt changed library');
  assert(writes.length === 0, 'Excerpt issued progress/active-tab commands');
  report.progress = 'Library unchanged; no progress, active-tab or library writes';
  await page.screenshot({ path: '.playwright-cli/excerpt-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile horizontal overflow');
  await page.screenshot({ path: '.playwright-cli/excerpt-mobile.png' });
  report.mobile = '390px: no horizontal overflow';
  await page.setViewportSize({ width: 1365, height: 950 }); await page.goto(origin + '/feed');
  await page.locator('.composer-action').filter({ hasText: 'Отрывки' }).click();
  await page.locator('.attach-modal .pick').filter({ hasText: 'Браузерный отрывок' }).click();
  await page.locator('.attach-modal').getByRole('button', { name: 'Подтвердить' }).click();
  const postResponse = page.waitForResponse(response => /\/social\/posts\/$/.test(response.url()) && response.request().method() === 'POST');
  await page.getByTitle('Опубликовать', { exact: true }).click();
  const post = await (await postResponse).json(); assert(post.attachments_data?.some(row => row.content_type === 'excerpt'), 'Post excerpt missing');
  await page.locator('.post-card .excerpt-card').first().waitFor();
  report.post = 'Active composer: picker, publish and separate excerpt card';
  const chats = await (await page.request.get(api + '/social/private-chats/', { headers })).json();
  const chat = (chats.results || chats)[0]; assert(chat?.id, 'No fixture chat');
  await page.goto(origin + `/chats/${chat.public_id || chat.id}?type=private`);
  await page.locator('.input-action').first().click();
  await page.locator('.attach-menu').getByRole('button', { name: 'Отрывок', exact: true }).click();
  await page.locator('.attach-picker-modal .pick').filter({ hasText: 'Браузерный отрывок' }).click();
  await page.locator('.attach-picker-modal').getByRole('button', { name: 'Готово' }).click();
  const messageResponse = page.waitForResponse(response => /\/messages\/$/.test(response.url()) && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Отправить сообщение', exact: true }).click();
  const message = await (await messageResponse).json(); assert(message.attachments?.some(row => row.type === 'excerpt'), 'Chat excerpt missing');
  await page.locator('.message-body .excerpt-card').first().waitFor();
  report.chat = 'Private chat: picker, send and separate excerpt card';
  await page.request.patch(api + `/anime/excerpts/${saved.id}/`, { headers, data: { title: 'Обновлённая карточка', end: 13.5 } });
  await page.waitForFunction(() => document.querySelector('.message-body .excerpt-card')?.textContent.includes('Обновлённая карточка'), { timeout: 20000 });
  report.liveCard = 'Already-open chat card updated after server edit';
  await page.request.patch(api + `/anime/excerpts/${saved.id}/`, { headers, data: { shared: false } });
  await page.waitForFunction(() => document.querySelector('.message-body .excerpt-card')?.textContent.includes('Отрывок недоступен'), { timeout: 20000 });
  assert((await page.request.get(api + '/anime/excerpts/shared/' + shared.share_path.split('/').pop() + '/')).status() === 404, 'Revoked guest link still works');
  report.revocation = 'Open attachment becomes unavailable; old link returns 404';
  assert(!pageErrors.length, 'Browser runtime errors: ' + pageErrors.join('; '));
  return report;
}
