import { afterEach, beforeEach, expect, it, vi } from 'vitest'
const { register, apply, reload } = vi.hoisted(() => ({ register: vi.fn(), apply: vi.fn(async () => undefined), reload: vi.fn() }))
vi.mock('virtual:pwa-register', () => ({ registerSW: register }))
beforeEach(() => {
  vi.resetModules(); vi.clearAllMocks(); register.mockReturnValue(apply)
  Object.defineProperty(window, 'matchMedia', { configurable: true, value: vi.fn(() => ({ matches: false, addEventListener: vi.fn() })) })
  Object.defineProperty(navigator, 'serviceWorker', { configurable: true, value: Object.assign(new EventTarget(), { controller: null }) })
  vi.stubGlobal('location', { reload })
  Object.defineProperty(window, 'isSecureContext', { configurable: true, value: true })
  vi.spyOn(window, 'setInterval').mockReturnValue(0 as unknown as ReturnType<typeof setInterval>)
})
afterEach(() => { vi.useRealTimers(); vi.restoreAllMocks(); vi.unstubAllGlobals() })
it('registers once and does not activate an update without a user action', async () => {
  const { startPwa, usePwa } = await import('./usePwa')
  startPwa(); startPwa()
  expect(register).toHaveBeenCalledTimes(1)
  register.mock.calls[0]![0].onNeedRefresh()
  expect(usePwa().needsRefresh.value).toBe(true)
  expect(apply).not.toHaveBeenCalled()
  const updating = usePwa().update()
  Object.assign(navigator.serviceWorker, { controller: {} })
  navigator.serviceWorker.dispatchEvent(new Event('controllerchange'))
  await updating
  expect(apply).toHaveBeenCalledWith(true)
  expect(reload).toHaveBeenCalledOnce()
})
it('tracks offline state and defers update until connectivity returns', async () => {
  const { startPwa, usePwa } = await import('./usePwa')
  startPwa(); window.dispatchEvent(new Event('offline'))
  expect(usePwa().online.value).toBe(false)
  await usePwa().update(); expect(apply).not.toHaveBeenCalled()
  window.dispatchEvent(new Event('online')); expect(usePwa().online.value).toBe(true)
})
it('retains a native install prompt and confirms installation from appinstalled', async () => {
  const { startPwa, usePwa } = await import('./usePwa')
  startPwa()
  const event = Object.assign(new Event('beforeinstallprompt', { cancelable: true }), {
    prompt: vi.fn(async () => undefined), userChoice: Promise.resolve({ outcome: 'accepted' }),
  })
  window.dispatchEvent(event)
  expect(event.defaultPrevented).toBe(true); expect(usePwa().canInstall.value).toBe(true)
  await usePwa().install(); expect(event.prompt).toHaveBeenCalledOnce()
  expect(usePwa().installed.value).toBe(false)
  window.dispatchEvent(new Event('appinstalled')); expect(usePwa().installed.value).toBe(true)
})
it('reports a failed installation instead of leaving files loading indefinitely', async () => {
  vi.useFakeTimers()
  const { startPwa, usePwa } = await import('./usePwa')
  startPwa()
  const worker = Object.assign(new EventTarget(), { state: 'installing' })
  const reg = Object.assign(new EventTarget(), { active: null, waiting: null, installing: worker as typeof worker | null, update: vi.fn(async () => undefined) })
  register.mock.calls[0]![0].onRegisteredSW('/sw.js', reg)
  await Promise.resolve()
  expect(reg.update).not.toHaveBeenCalled()
  register.mock.calls[0]![0].onOfflineReady()
  reg.installing = null; worker.state = 'redundant'; worker.dispatchEvent(new Event('statechange'))
  expect(usePwa().offlineReady.value).toBe(false)
  expect(usePwa().error.value).toContain('Не удалось сохранить файлы')
  register.mock.calls[0]![0].onOfflineReady()
  expect(usePwa().error.value).toBe('')
  expect(usePwa().offlineReady.value).toBe(true)
})
it('keeps the current offline version usable when an update fails', async () => {
  const { startPwa, usePwa } = await import('./usePwa')
  startPwa()
  const worker = Object.assign(new EventTarget(), { state: 'installing' })
  const reg = Object.assign(new EventTarget(), { active: { state: 'activated' }, waiting: null, installing: worker as typeof worker | null, update: vi.fn(async () => undefined) })
  register.mock.calls[0]![0].onRegisteredSW('/sw.js', reg)
  await Promise.resolve()
  reg.installing = null; worker.state = 'redundant'; worker.dispatchEvent(new Event('statechange'))
  expect(usePwa().offlineReady.value).toBe(true)
  expect(usePwa().error.value).toContain('Не удалось загрузить обновление')
  register.mock.calls[0]![0].onNeedRefresh()
  expect(usePwa().error.value).toBe('')
  expect(usePwa().needsRefresh.value).toBe(true)
})
it('does not show a failure when a successfully activated worker is replaced', async () => {
  const { startPwa, usePwa } = await import('./usePwa')
  startPwa()
  const worker = Object.assign(new EventTarget(), { state: 'installing' })
  const reg = Object.assign(new EventTarget(), { active: null, waiting: null, installing: worker as typeof worker | null, update: vi.fn(async () => undefined) })
  register.mock.calls[0]![0].onRegisteredSW('/sw.js', reg)
  await Promise.resolve()
  worker.state = 'activated'; worker.dispatchEvent(new Event('statechange'))
  reg.installing = null; worker.state = 'redundant'; worker.dispatchEvent(new Event('statechange'))
  expect(usePwa().error.value).toBe('')
})
it('reloads a cold client even when Workbox does not emit its reload callback', async () => {
  const { startPwa, usePwa } = await import('./usePwa')
  startPwa(); register.mock.calls[0]![0].onNeedRefresh()
  const updating = usePwa().update()
  expect(usePwa().updating.value).toBe(true)
  await Promise.resolve()
  Object.assign(navigator.serviceWorker, { controller: {} })
  navigator.serviceWorker.dispatchEvent(new Event('controllerchange'))
  register.mock.calls[0]![0].onNeedReload()
  await updating
  expect(reload).toHaveBeenCalledOnce()
  expect(usePwa().updating.value).toBe(false)
})
it('stops waiting and allows retry when a worker cannot activate', async () => {
  vi.useFakeTimers()
  const { startPwa, usePwa } = await import('./usePwa')
  startPwa(); register.mock.calls[0]![0].onNeedRefresh()
  const updating = usePwa().update()
  await vi.advanceTimersByTimeAsync(15000)
  await updating
  expect(usePwa().error.value).toContain('Обновление не удалось')
  expect(usePwa().updating.value).toBe(false)
  expect(reload).not.toHaveBeenCalled()
})
