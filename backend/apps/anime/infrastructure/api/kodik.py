logger = logging.getLogger(__name__)

KODIK_API_TIMEOUT = (5, 30)


class KodikAPI:
    def __init__(self, token: str = KODIK_API_TOKEN, base_url: str = KODIK_API_BASE):
        self.token = token
        self.base_url = (base_url or "").rstrip("/")

    def _get(self, path: str, params: Optional[Dict[str, Any]] = None, retries: int = 3) -> Dict[str, Any]:
        if not self.base_url or not self.token:
            raise RuntimeError("Kodik integration is not configured")
        url = f"{self.base_url}{path}"
        payload: Dict[str, Any] = {"token": self.token}
        if params:
            payload.update(params)
        attempt = 0
        while True:
            attempt += 1
            response = requests.get(url, params=payload, timeout=KODIK_API_TIMEOUT)
            if response.status_code == 429:
                if attempt >= retries:
                    response.raise_for_status()
                retry_after = 1
                try:
                    retry_after = max(1, int(response.headers.get("Retry-After", "1")))
                except (TypeError, ValueError):
                    retry_after = min(2 ** attempt, 30)
                time.sleep(retry_after)
                continue
            response.raise_for_status()
            return response.json()

